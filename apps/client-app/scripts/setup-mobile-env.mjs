#!/usr/bin/env node

/**
 * Generates .env.production.local from .env.mobile-secrets.{mode}.local
 * so `next build` (always production) embeds the correct NEXT_PUBLIC_* values.
 */

import { chmodSync, existsSync, readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const exampleFile = resolve(rootDir, '.env.mobile-secrets.example');
const supportedModes = ['staging', 'production'];
const requiredKeys = ['NEXT_PUBLIC_API_URL'];

function parseEnvFile(content) {
  const vars = {};

  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const match = trimmed.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
    if (match) {
      vars[match[1]] = match[2];
    }
  }

  return vars;
}

function generateEnvLocal(secrets, sourceName, mode) {
  const lines = [
    `# Auto-generated by setup-mobile-env.mjs from ${sourceName}`,
    '# Do not commit this file (gitignored via .env*.local)',
    '',
    `NEXT_PUBLIC_APP_ENV=${mode}`,
    '',
  ];

  for (const [key, value] of Object.entries(secrets)) {
    if (key === 'NEXT_PUBLIC_APP_ENV') continue;
    lines.push(`${key}=${value}`);
  }

  return lines.join('\n') + '\n';
}

function main() {
  const mode = process.argv[2] || 'production';

  if (!supportedModes.includes(mode)) {
    console.error(`❌ Error: Invalid mode "${mode}"`);
    console.error('Usage: node scripts/setup-mobile-env.mjs [staging|production]\n');
    process.exit(1);
  }

  const sourceName = `.env.mobile-secrets.${mode}.local`;
  const secretsFile = resolve(rootDir, sourceName);
  // next build always loads production env files
  const outputFile = resolve(rootDir, '.env.production.local');

  if (!existsSync(secretsFile)) {
    console.error(`❌ Error: ${secretsFile} not found\n`);
    console.error('To set up this mobile environment:');
    console.error(`  1. cp ${exampleFile} ${sourceName}`);
    console.error(`  2. Fill in the ${mode} values in ${sourceName}`);
    console.error(`  3. Run this script again with "${mode}"\n`);
    process.exit(1);
  }

  const secrets = parseEnvFile(readFileSync(secretsFile, 'utf-8'));
  const missingKeys = requiredKeys.filter((key) => !secrets[key]?.trim());

  if (missingKeys.length > 0) {
    console.error(`❌ Error: Missing or empty values in ${secretsFile}:`);
    missingKeys.forEach((key) => console.error(`   - ${key}`));
    process.exit(1);
  }

  const placeholderPattern = /^###.*###$/;
  const placeholderKeys = Object.entries(secrets)
    .filter(([, value]) => placeholderPattern.test(value.replace(/['"]/g, '')))
    .map(([key]) => key);

  if (placeholderKeys.length > 0) {
    console.error(`❌ Error: Placeholder values remain in ${secretsFile}:`);
    placeholderKeys.forEach((key) => console.error(`   - ${key}`));
    process.exit(1);
  }

  const envContent = generateEnvLocal(secrets, sourceName, mode);

  if (!existsSync(outputFile) || readFileSync(outputFile, 'utf-8') !== envContent) {
    writeFileSync(outputFile, envContent, { mode: 0o600 });
    console.log(`✅ Generated .env.production.local from ${sourceName}`);
  } else {
    console.log(`✅ .env.production.local is already up to date`);
  }

  chmodSync(outputFile, 0o600);
}

main();
